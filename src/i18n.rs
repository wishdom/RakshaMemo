//! Interface text in English, French, and Japanese.
//!
//! Each language is one [`Text`] table, so a string missing from any language
//! fails to compile. Templates number their values (`{0}`, `{1}`) because word
//! order differs between languages; [`fill`] substitutes them. Pairs such as
//! `[one, other]` are plural forms, chosen by [`plural`].
//!
//! The language is per thread: the interface runs on one thread, and tests
//! (each on its own thread) cannot affect one another.

use std::cell::Cell;
use std::fmt::Display;

use rakshamemo::settings::Language;
use rakshamemo::strength::{Suggestion, Warning};

thread_local! {
    static CURRENT: Cell<Language> = const { Cell::new(Language::English) };
}

pub fn set(language: Language) {
    CURRENT.with(|current| current.set(language));
}

pub fn language() -> Language {
    CURRENT.with(Cell::get)
}

/// The text for the current language.
pub fn t() -> &'static Text {
    match language() {
        Language::English => &EN,
        Language::French => &FR,
        Language::Japanese => &JA,
    }
}

/// Replace `{0}`, `{1}`, … in `template` with `values`.
pub fn fill(template: &str, values: &[&dyn Display]) -> String {
    let mut text = template.to_owned();
    for (index, value) in values.iter().enumerate() {
        text = text.replace(&format!("{{{index}}}"), &value.to_string());
    }
    text
}

/// The plural form of `forms` (`[one, other]`) for `count`, with `{0}`
/// replaced by the count.
pub fn plural(count: usize, forms: [&str; 2]) -> String {
    let one = match language() {
        Language::English => count == 1,
        // French uses the singular for zero and one.
        Language::French => count <= 1,
        Language::Japanese => true,
    };
    fill(if one { forms[0] } else { forms[1] }, &[&count])
}

/// A user-facing description of an error. The library's messages are in
/// English; the common ones are recognized and translated.
pub fn describe(error: &anyhow::Error) -> String {
    if error
        .chain()
        .any(|cause| cause.is::<rakshamemo::crypto::IncorrectPassword>())
    {
        t().incorrect_password.to_owned()
    } else {
        format!("{error:#}")
    }
}

pub fn warning(warning: Warning) -> &'static str {
    let index = match warning {
        Warning::StraightRowsOfKeysAreEasyToGuess => 0,
        Warning::ShortKeyboardPatternsAreEasyToGuess => 1,
        Warning::RepeatsLikeAaaAreEasyToGuess => 2,
        Warning::RepeatsLikeAbcAbcAreOnlySlightlyHarderToGuess => 3,
        Warning::ThisIsATop10Password => 4,
        Warning::ThisIsATop100Password => 5,
        Warning::ThisIsACommonPassword => 6,
        Warning::ThisIsSimilarToACommonlyUsedPassword => 7,
        Warning::SequencesLikeAbcAreEasyToGuess => 8,
        Warning::RecentYearsAreEasyToGuess => 9,
        Warning::AWordByItselfIsEasyToGuess => 10,
        Warning::DatesAreOftenEasyToGuess => 11,
        Warning::NamesAndSurnamesByThemselvesAreEasyToGuess => 12,
        Warning::CommonNamesAndSurnamesAreEasyToGuess => 13,
    };
    t().warnings[index]
}

pub fn suggestion(suggestion: Suggestion) -> &'static str {
    let index = match suggestion {
        Suggestion::UseAFewWordsAvoidCommonPhrases => 0,
        Suggestion::NoNeedForSymbolsDigitsOrUppercaseLetters => 1,
        Suggestion::AddAnotherWordOrTwo => 2,
        Suggestion::CapitalizationDoesntHelpVeryMuch => 3,
        Suggestion::AllUppercaseIsAlmostAsEasyToGuessAsAllLowercase => 4,
        Suggestion::ReversedWordsArentMuchHarderToGuess => 5,
        Suggestion::PredictableSubstitutionsDontHelpVeryMuch => 6,
        Suggestion::UseALongerKeyboardPatternWithMoreTurns => 7,
        Suggestion::AvoidRepeatedWordsAndCharacters => 8,
        Suggestion::AvoidSequences => 9,
        Suggestion::AvoidRecentYears => 10,
        Suggestion::AvoidYearsThatAreAssociatedWithYou => 11,
        Suggestion::AvoidDatesAndYearsThatAreAssociatedWithYou => 12,
    };
    t().suggestions[index]
}

/// A rough duration such as "3 hours" or "centuries".
pub fn duration(seconds: f64) -> String {
    const MINUTE: f64 = 60.0;
    const HOUR: f64 = MINUTE * 60.0;
    const DAY: f64 = HOUR * 24.0;
    const MONTH: f64 = DAY * 31.0;
    const YEAR: f64 = MONTH * 12.0;
    let text = t();
    let units = [
        (YEAR * 100.0, YEAR, text.years),
        (YEAR, MONTH, text.months_count),
        (MONTH, DAY, text.days),
        (DAY, HOUR, text.hours),
        (HOUR, MINUTE, text.minutes),
        (MINUTE, 1.0, text.seconds),
    ];
    if seconds < 1.0 {
        return text.less_than_a_second.to_owned();
    }
    if seconds >= YEAR * 100.0 {
        return text.centuries.to_owned();
    }
    let (_, unit, forms) = units
        .into_iter()
        .rev()
        .find(|(limit, _, _)| seconds < *limit)
        .unwrap_or(units[0]);
    plural((seconds / unit) as usize, forms)
}

/// The toolbar clock and its longer hover text, in the current language.
pub fn clock(now: &chrono::DateTime<chrono::Local>, clock_24h: bool) -> (String, String) {
    use chrono::{Datelike, Timelike};
    let text = t();
    let weekday = now.weekday().num_days_from_monday() as usize;
    let time = if clock_24h {
        now.format("%H:%M").to_string()
    } else {
        let (pm, hour) = now.hour12();
        fill(
            text.time_12h,
            &[
                &hour,
                &format!("{:02}", now.minute()),
                &if pm { text.pm } else { text.am },
            ],
        )
    };
    let date = now.format("%Y-%m-%d").to_string();
    let short = fill(text.clock, &[&text.weekdays_short[weekday], &date, &time]);
    let long = fill(
        text.long_date,
        &[
            &text.weekdays[weekday],
            &text.months[now.month0() as usize],
            &now.day(),
            &now.year(),
            &now.month(),
        ],
    );
    (short, long)
}

/// A local date and time such as "2026-10-14 at 19:44".
pub fn date_time(date: &chrono::DateTime<chrono::Local>) -> String {
    fill(
        t().date_at_time,
        &[&date.format("%Y-%m-%d"), &date.format("%H:%M")],
    )
}

